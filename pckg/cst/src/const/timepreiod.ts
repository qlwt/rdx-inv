export const timeperiod_second = 1e3
export const timeperiod_minute = timeperiod_second * 60
export const timeperiod_hour = timeperiod_minute * 60
export const timeperiod_day = timeperiod_hour * 24
export const timeperiod_week = timeperiod_day * 7
export const timeperiod_month = timeperiod_day * 31
export const timeperiod_year = timeperiod_day * 365
